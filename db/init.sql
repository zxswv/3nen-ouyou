-- -------------------------------------------------------------
-- 1. 部署テーブル
-- -------------------------------------------------------------
CREATE TABLE departments (
    department_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_name VARCHAR(50) NOT NULL,
    max_members     INTEGER     NOT NULL DEFAULT 50 CHECK (max_members > 0)
);

-- -------------------------------------------------------------
-- 2. ユーザーテーブル（ログインIDは email）
-- -------------------------------------------------------------
CREATE TABLE users (
    user_id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    password         VARCHAR(255) NOT NULL,
    name             VARCHAR(50)  NOT NULL,
    department_id    INTEGER      NOT NULL REFERENCES departments (department_id),
    role             VARCHAR(20)  NOT NULL CHECK (role IN ('ADMIN', 'GENERAL')),
    email            VARCHAR(255) NOT NULL UNIQUE,
    phone_number     VARCHAR(20),
    current_location VARCHAR(50)
);
CREATE INDEX idx_users_department_id ON users (department_id);

-- -------------------------------------------------------------
-- 3. 勤怠テーブル
--    (user_id, target_date) の一意制約で二重打刻を防ぐ
-- -------------------------------------------------------------
CREATE TABLE attendances (
    attendance_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        INTEGER       NOT NULL REFERENCES users (user_id),
    target_date    DATE          NOT NULL,
    clock_in_time  TIMESTAMP,
    clock_out_time TIMESTAMP,
    work_location  VARCHAR(50),
    latitude       DECIMAL(10, 7),
    longitude      DECIMAL(10, 7),
    CONSTRAINT uq_attendances_user_date UNIQUE (user_id, target_date),
    CONSTRAINT ck_attendances_clock_order
        CHECK (clock_out_time IS NULL OR clock_in_time IS NULL OR clock_out_time >= clock_in_time)
);

-- -------------------------------------------------------------
-- 4. 申請テーブル
--    version は楽観的ロック用（詳細設計書 10章）
-- -------------------------------------------------------------
CREATE TABLE applications (
    application_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           INTEGER     NOT NULL REFERENCES users (user_id),
    application_type  VARCHAR(20) NOT NULL CHECK (application_type IN ('VACATION', 'OVERTIME')),
    target_date_start DATE        NOT NULL,
    target_date_end   DATE        NOT NULL,
    reason            TEXT,
    status            VARCHAR(20) NOT NULL DEFAULT 'PENDING'
                          CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    applied_at        TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version           INTEGER     NOT NULL DEFAULT 0,
    CONSTRAINT ck_applications_date_order CHECK (target_date_end >= target_date_start)
);
CREATE INDEX idx_applications_user_id ON applications (user_id);
CREATE INDEX idx_applications_status ON applications (status);

